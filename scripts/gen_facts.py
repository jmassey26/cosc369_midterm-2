#!/usr/bin/env python3
"""
gen_facts.py

Reads the two raw input files (class_schedule.txt and faculty_info.txt)
and writes Prolog facts to a .pl file. Python does the reading and
translating; Prolog (prolog/rules.pl) does the reasoning.

Usage:
    python3 scripts/gen_facts.py data/class_schedule.txt data/faculty_info.txt prolog/facts.pl

Facts written:
    faculty(Id, 'Display Name', 'Department').
    policy(Id, DaytimeEndMin, EveningLenMin, EveningCutoffMin).
    course(Code, 'Title', LecturerId).
    meets(Code, Day, StartMin, EndMin, 'Room').
Times are minutes since midnight. Day is monday..friday.
"""
import sys

DAY_NAMES = {"M": "monday", "T": "tuesday", "W": "wednesday",
             "R": "thursday", "F": "friday"}


def to_minutes(hhmm):
    h, m = hhmm.split(":")
    return int(h) * 60 + int(m)


def q(text):
    """Quote a string as a Prolog atom."""
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def data_lines(path):
    with open(path, encoding="utf-8") as f:
        for n, raw in enumerate(f, 1):
            line = raw.strip()
            if line and not line.startswith("#"):
                yield n, [p.strip() for p in line.split("|")]


def main():
    if len(sys.argv) != 4:
        print(f"Usage: {sys.argv[0]} <class_schedule.txt> <faculty_info.txt> <facts.pl>",
              file=sys.stderr)
        sys.exit(1)
    classes_path, faculty_path, out_path = sys.argv[1:]

    out = ["% Generated by scripts/gen_facts.py. Do not edit by hand.",
           ":- discontiguous faculty/3, policy/4, course/3, meets/5.", ""]

    for n, f in data_lines(faculty_path):
        if len(f) != 6:
            print(f"{faculty_path}:{n}: skipped malformed line", file=sys.stderr)
            continue
        fid, name, dept, day_end, ev_len, ev_cut = f
        out.append(f"faculty({fid}, {q(name)}, {q(dept)}).")
        out.append(f"policy({fid}, {to_minutes(day_end)}, {int(ev_len)}, {to_minutes(ev_cut)}).")

    out.append("")
    for n, c in data_lines(classes_path):
        if len(c) != 7:
            print(f"{classes_path}:{n}: skipped malformed line", file=sys.stderr)
            continue
        code, title, lec, days, start, end, room = c
        code_atom = q(code.lower())
        out.append(f"course({code_atom}, {q(title)}, {lec}).")
        for d in days:
            if d in DAY_NAMES:
                out.append(f"meets({code_atom}, {DAY_NAMES[d]}, "
                           f"{to_minutes(start)}, {to_minutes(end)}, {q(room)}).")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
