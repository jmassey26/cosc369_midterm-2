#!/usr/bin/env python3
"""
import_xlsx.py

Converts the department's Excel schedule (CTEC Fall 2026) into the two
text files the C program reads:

    data/class_schedule.txt   CODE|TITLE|LECTURER_ID|DAYS|START|END|ROOM
    data/faculty_info.txt     ID|NAME|DEPT|DAYTIME_END|EVENING_LEN|EVENING_CUTOFF

The spreadsheet only lists classes and instructor names. It has no
faculty information, so the faculty file is built from the instructor
names plus the default office-hour policy set below.

The spreadsheet is hand-typed and has inconsistencies. Every repair or
skipped row is printed so nothing changes silently.

Usage:
    python3 scripts/import_xlsx.py data/CTEC_Fall_2026_Schedule.xlsx data
Needs: python3 -m pip install openpyxl
"""
import datetime
import re
import sys

import openpyxl

DEPARTMENT = "CTEC"
# Default office-hour policy given to every instructor.
DAYTIME_END = "13:00"     # latest end of a daytime office-hour block
EVENING_LEN = 120         # minutes of office hours before the evening class
EVENING_CUTOFF = "16:00"  # classes starting at or after this are "evening"


def clean(text):
    return re.sub(r"\s+", " ", str(text)).strip()


def split_name(raw):
    """Return (id, display) for names like 'Dr. Stone, D. B.' or 'Eugene T. Harris'."""
    name = clean(raw)
    name = re.sub(r"^Dr\.?\s+", "", name)
    if "," in name:
        last, first = [p.strip() for p in name.split(",", 1)]
        display = f"{first} {last}".strip()
    else:
        parts = name.split(" ")
        last = parts[-1]
        display = name
    return re.sub(r"[^a-z]", "", last.lower()), display


def fmt(t):
    return f"{t.hour:02d}:{t.minute:02d}"


def fix_times(code, begin, end, notes):
    """Return (start, end) as datetime.time, or None if unusable."""
    if not isinstance(begin, datetime.time) or not isinstance(end, datetime.time):
        notes.append(f"SKIPPED {code}: no meeting time ({begin!r})")
        return None
    s = begin.hour * 60 + begin.minute
    e = end.hour * 60 + end.minute
    if e == s:
        notes.append(f"SKIPPED {code}: start and end are both {fmt(begin)}")
        return None
    if e < s:
        if e < 12 * 60 and e + 12 * 60 > s:
            fixed = datetime.time((e // 60 + 12) % 24, e % 60)
            notes.append(f"FIXED   {code}: end {fmt(end)} is before start "
                         f"{fmt(begin)}; read as {fmt(fixed)} (PM typo)")
            return begin, fixed
        notes.append(f"SKIPPED {code}: end {fmt(end)} is before start {fmt(begin)}")
        return None
    return begin, end


def main():
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <schedule.xlsx> <output_dir>", file=sys.stderr)
        sys.exit(1)
    xlsx, outdir = sys.argv[1:]

    ws = openpyxl.load_workbook(xlsx, data_only=True).active
    notes, rows, faculty = [], [], {}

    for r in list(ws.iter_rows(values_only=True))[1:]:
        code, title, _cr, days, begin, end, room, instr = r[:8]
        if not code:
            continue
        code, title = clean(code), clean(title)
        times = fix_times(code, begin, end, notes)
        days = clean(days or "")
        if times is None or not days:
            continue
        fid, display = split_name(instr)
        # keep the most complete spelling of each instructor's name
        if fid not in faculty or len(display) > len(faculty[fid]):
            if fid in faculty:
                notes.append(f"MERGED  '{faculty[fid]}' and '{display}' treated as one instructor")
            faculty[fid] = display
        room = clean(room).capitalize() if str(room).lower() in ("online", "dept") else clean(room)
        rows.append((code, title, fid, days, fmt(times[0]), fmt(times[1]), room))

    with open(f"{outdir}/class_schedule.txt", "w", encoding="utf-8") as f:
        f.write("# Generated by scripts/import_xlsx.py from the CTEC Fall 2026 spreadsheet.\n")
        f.write("# CODE|TITLE|LECTURER_ID|DAYS|START|END|ROOM\n")
        for row in rows:
            f.write("|".join(row) + "\n")

    with open(f"{outdir}/faculty_info.txt", "w", encoding="utf-8") as f:
        f.write("# Generated by scripts/import_xlsx.py (default office-hour policy).\n")
        f.write("# ID|NAME|DEPT|DAYTIME_END|EVENING_LEN|EVENING_CUTOFF\n")
        for fid in sorted(faculty):
            f.write(f"{fid}|{faculty[fid]}|{DEPARTMENT}|{DAYTIME_END}|{EVENING_LEN}|{EVENING_CUTOFF}\n")

    print(f"{len(rows)} class rows, {len(faculty)} instructors written to {outdir}/")
    for n in sorted(set(notes)):
        print("  " + n)


if __name__ == "__main__":
    main()
